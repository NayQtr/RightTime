"""Generates qatar/design/flutter/herzone_tokens.dart from qatar/design/tokens.json (single source of truth, also used by
build_tokens_css.py for the website). Run: python3 build_tokens_dart.py

The output is plain Flutter (package:flutter only): colours for light and dark, a ColorScheme for each, text styles for
Arabic and English, spacing, radii, shadows and motion. Fonts are referenced by family name; the app bundles the same
font files the website uses (IBM Plex Sans Arabic, Alexandria)."""
import json
import pathlib
import re

HERE = pathlib.Path(__file__).parent
t = json.loads((HERE / "tokens.json").read_text())
OUT = HERE / "flutter" / "herzone_tokens.dart"


def color(hexstr):
    h = hexstr.lstrip("#").upper()
    if len(h) == 6:
        return f"Color(0xFF{h})"
    if len(h) == 8:  # CSS #RRGGBBAA -> Flutter 0xAARRGGBB
        return f"Color(0x{h[6:]}{h[:6]})"
    raise ValueError(hexstr)


def num(x):
    f = float(x)
    return f"{f:.1f}" if f.is_integer() else repr(f)


def px(v):
    return num(str(v).removesuffix("px"))


def items(group):
    return [(k, v) for k, v in group.items() if not k.startswith("$")]


def ident(k):
    return k if re.match(r"^[A-Za-z_]", k) else f"s{k}"


def families(ref):
    name = ref[len("{font.family."):-1]
    fams = t["font"]["family"][name]["$value"]
    real = [f for f in fams if f not in ("system-ui", "sans-serif")]
    return real[0], real[1:]


def weight(ref):
    w = int(t["font"]["weight"][ref[len("{font.weight."):-1]]["$value"])
    return f"FontWeight.w{w}"


def letter_spacing(v, size):
    v = str(v)
    if v.endswith("em"):
        return num(round(float(v[:-2]) * size, 3))
    return num(v.removesuffix("px") or 0)


lines = [
    "// GENERATED by qatar/design/build_tokens_dart.py from qatar/design/tokens.json. Do not edit by hand.",
    f"// {t['$description']}",
    "// ignore_for_file: constant_identifier_names",
    "import 'package:flutter/material.dart';",
    "",
    "/// Colour roles of one theme (light or dark). Contrast pairs are checked in tokens.json ($contrastPairs).",
    "@immutable",
    "class HzColors {",
]
roles = list(t["color"]["light"].keys())
assert roles == list(t["color"]["dark"].keys()), "light and dark must define the same roles"
lines += [f"  final Color {r};" for r in roles]
lines.append("  const HzColors({" + ", ".join(f"required this.{r}" for r in roles) + "});")
for theme in ("light", "dark"):
    vals = ", ".join(f"{r}: {color(v['$value'])}" for r, v in t["color"][theme].items())
    lines.append(f"  static const {theme} = HzColors({vals});")
lines += [
    "",
    "  /// Material 3 colour scheme built from the HerZone roles.",
    "  ColorScheme scheme(Brightness brightness) => ColorScheme(",
    "        brightness: brightness,",
    "        primary: primary, onPrimary: onPrimary, primaryContainer: primarySubtle, onPrimaryContainer: text,",
    "        secondary: seat, onSecondary: seatInk, tertiary: info, onTertiary: onPrimary,",
    "        error: danger, onError: onDanger, surface: surface, onSurface: text, onSurfaceVariant: textMuted,",
    "        surfaceContainerLowest: bg, surfaceContainerLow: surfaceSunken, outline: borderStrong, outlineVariant: border,",
    "      );",
    "}",
    "",
]

lines.append("/// Spacing in logical pixels (4-point scale). touchTarget is the minimum tap size.")
lines.append("abstract final class HzSpace {")
lines += [f"  static const double {ident(k)} = {px(v['$value'])};" for k, v in items(t["space"])]
lines += ["}", ""]

lines.append("abstract final class HzRadius {")
lines += [f"  static const double {k} = {px(v['$value'])};" for k, v in items(t["radius"])]
lines += ["}", ""]

lines.append("/// Shadows for the light theme. In dark theme shadows are not visible: raise surfaces by one step instead.")
lines.append("abstract final class HzElevation {")
for k, v in items(t["elevation"]):
    if v["$type"] != "shadow":
        continue
    s = v["$value"]
    lines.append(f"  static const List<BoxShadow> e{k} = [BoxShadow(color: {color(s['color'])}, offset: Offset({px(s['offsetX'])}, {px(s['offsetY'])}), "
                 f"blurRadius: {px(s['blur'])}, spreadRadius: {px(s['spread'])})];")
lines += ["}", ""]

m = t["motion"]
ms = lambda k: int(str(m[k]["$value"]).removesuffix("ms"))
lines += [
    "/// Durations; with reduced motion (MediaQuery.disableAnimations) use Duration.zero except short opacity fades.",
    "abstract final class HzMotion {",
    f"  static const Duration fast = Duration(milliseconds: {ms('fast')});",
    f"  static const Duration base = Duration(milliseconds: {ms('base')});",
    f"  static const Duration slow = Duration(milliseconds: {ms('slow')});",
    "  static const Curve easing = Cubic(" + ", ".join(num(x) for x in m["easing"]["$value"]) + ");",
    "}",
    "",
    "/// Text styles per language. Arabic uses taller lines; English display sizes are tighter.",
    "abstract final class HzType {",
]
for lang in ("ar", "en"):
    for role, v in t["type"][lang].items():
        s = v["$value"]
        fam, fallback = families(s["fontFamily"])
        size = float(s["fontSize"].removesuffix("px"))
        fb = ", ".join(f"'{f}'" for f in fallback)
        lines.append(f"  static const TextStyle {lang}{role[0].upper()}{role[1:]} = TextStyle(fontFamily: '{fam}', fontFamilyFallback: [{fb}], "
                     f"fontSize: {px(s['fontSize'])}, height: {num(s['lineHeight'])}, fontWeight: {weight(s['fontWeight'])}, "
                     f"letterSpacing: {letter_spacing(s['letterSpacing'], size)});")
lines += [
    "",
    "  /// Material TextTheme for a language code ('ar' or 'en').",
    "  static TextTheme textTheme(String lang) {",
    "    final ar = lang == 'ar';",
    "    return TextTheme(",
    "      displaySmall: ar ? arDisplay : enDisplay, headlineMedium: ar ? arH1 : enH1, titleLarge: ar ? arH2 : enH2,",
    "      bodyLarge: ar ? arBody : enBody, bodyMedium: ar ? arBody : enBody, labelLarge: ar ? arLabel : enLabel, bodySmall: ar ? arCaption : enCaption,",
    "    );",
    "  }",
    "}",
    "",
    "/// ThemeData for HerZone in a brightness and language.",
    "ThemeData hzTheme(Brightness brightness, String lang) {",
    "  final c = brightness == Brightness.dark ? HzColors.dark : HzColors.light;",
    "  return ThemeData(",
    "    useMaterial3: true,",
    "    colorScheme: c.scheme(brightness),",
    "    scaffoldBackgroundColor: c.bg,",
    "    textTheme: HzType.textTheme(lang).apply(bodyColor: c.text, displayColor: c.text),",
    "    materialTapTargetSize: MaterialTapTargetSize.padded,",
    "  );",
    "}",
]

OUT.parent.mkdir(exist_ok=True)
OUT.write_text("\n".join(lines) + "\n")
print(f"wrote {OUT}")
