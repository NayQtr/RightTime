"""Copies the self-hosted fonts into qatar/web/fonts and writes fonts.css (spec 2026-10-29 §2.2).

Source: the @fontsource packages (install them anywhere: npm i @fontsource/alexandria@5.1.0 @fontsource/ibm-plex-sans-arabic@5.1.0).
Run: python3 build_fonts.py <path to node_modules/@fontsource>
Only Arabic and Latin subsets of the weights the app uses are copied; unicode-range comes from fontsource's per-weight CSS (<weight>.css).
"""
import pathlib
import re
import shutil
import sys

SRC = pathlib.Path(sys.argv[1])
OUT = pathlib.Path(__file__).parent.parent / "web" / "fonts"
FAMILIES = {"alexandria": ("Alexandria", [600, 700, 800]), "ibm-plex-sans-arabic": ("IBM Plex Sans Arabic", [400, 500, 600])}
SUBSETS = ["arabic", "latin"]

OUT.mkdir(parents=True, exist_ok=True)
faces = []
for pkg, (family, weights) in FAMILIES.items():
    shutil.copy(SRC / pkg / "LICENSE", OUT / f"OFL-{pkg}.txt")
    for w in weights:
        for sub in SUBSETS:
            name = f"{pkg}-{sub}-{w}-normal.woff2"
            shutil.copy(SRC / pkg / "files" / name, OUT / name)
            css = (SRC / pkg / f"{w}.css").read_text()
            block = re.search(r"/\* " + re.escape(f"{pkg}-{sub}-{w}-normal") + r" \*/\s*@font-face \{(.*?)\}", css, re.S).group(1)
            rng = re.search(r"unicode-range:\s*([^;]+);", block).group(1).strip()
            faces.append(f"@font-face {{ font-family: \"{family}\"; font-style: normal; font-weight: {w}; font-display: swap;\n"
                         f"  src: url(\"/fonts/{name}\") format(\"woff2\"); unicode-range: {rng}; }}")
(OUT / "fonts.css").write_text("/* GENERATED by qatar/design/build_fonts.py — self-hosted fonts (SIL OFL 1.1, see OFL-*.txt). */\n" + "\n".join(faces) + "\n")
print("wrote", len(faces), "faces to", OUT)
