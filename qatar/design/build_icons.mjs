// Generates qatar/web/icons.js from lucide-static (spec 2026-10-29 §2.3): one icon family, inline SVG, no emoji.
// Install the source anywhere (npm i lucide-static@0.460.0), then: node build_icons.mjs <path to lucide-static/icons>
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const NAMES = ["arrow-right", "arrow-left", "chevron-left", "chevron-right", "calendar-days", "clock", "map-pin", "users", "utensils", "coffee",
  "languages", "wallet", "phone", "message-circle", "house", "bell", "circle-user-round", "check", "info", "triangle-alert", "shield-check",
  "lock", "hand-heart", "book-open", "hourglass", "x", "ticket", "sparkle", "log-out", "trash-2", "flag", "star", "circle-check"];
const src = process.argv[2];
const icons = {};
for (const n of NAMES) {
  const svg = readFileSync(path.join(src, `${n}.svg`), "utf8");
  icons[n] = svg.replace(/<!--[\s\S]*?-->/g, "").replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/\s+/g, " ").trim();
}
const out = `// GENERATED by qatar/design/build_icons.mjs from lucide-static 0.460.0 — do not edit by hand.
// Lucide icons: ISC License, Copyright (c) for portions of Lucide are held by Cole Bemis 2013-2022 as part of Feather (MIT);
// all other copyright (c) for Lucide are held by Lucide Contributors 2022. https://lucide.dev/license
const ICONS = ${JSON.stringify(icons, null, 0).replace(/","/g, '",\n  "').replace(/^\{/, "{\n  ").replace(/\}$/, ",\n}")};

export const ICON_NAMES = Object.keys(ICONS);

// Decorative by default (aria-hidden): every icon sits next to visible text or inside a control with its own label.
export function icon(name, cls = "i") {
  const body = ICONS[name];
  if (!body) throw new Error(\`unknown icon: \${name}\`);
  return \`<svg class="\${cls}" aria-hidden="true" focusable="false" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">\${body}</svg>\`;
}
`;
const target = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "web", "icons.js");
writeFileSync(target, out);
console.log("wrote", NAMES.length, "icons to", target);
