// Builds the website's and the app's country lists from the one source, qatar/api/src/lib/countries.js.
//   node qatar/ops/build-countries.mjs
// Writes qatar/web/countries.js and qatar/app/lib/data/countries.dart. api/test/countries.test.mjs fails if the files
// on disk are not what this script produces, so the two lists can never drift apart.
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { COUNTRIES, DEFAULT_COUNTRY } from "../api/src/lib/countries.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const HEADER = "// Generated by qatar/ops/build-countries.mjs from qatar/api/src/lib/countries.js — do not edit by hand.";

// Dart: a single-quoted literal, or a double-quoted one when the name itself has an apostrophe (Côte d'Ivoire).
const dart = (s) => (s.includes("'") ? `"${s}"` : `'${s}'`);

export function webSource() {
  return `${HEADER}
// The countries the phone picker offers, sorted by English name. Israel is not offered (owner's decision, 11 Nov 2026).
export const DEFAULT_COUNTRY = ${JSON.stringify(DEFAULT_COUNTRY)};

export const COUNTRIES = [
${COUNTRIES.map((c) => `  { iso: ${JSON.stringify(c.iso)}, dial: ${JSON.stringify(c.dial)}, ar: ${JSON.stringify(c.ar)}, en: ${JSON.stringify(c.en)} },`).join("\n")}
];

// The chosen country, or Qatar when the stored choice is not one we offer any more.
export const countryByIso = (iso) => COUNTRIES.find((c) => c.iso === iso) || COUNTRIES.find((c) => c.iso === DEFAULT_COUNTRY);
`;
}

export function dartSource() {
  return `${HEADER}
// The countries the phone picker offers, sorted by English name. Israel is not offered (owner's decision, 11 Nov 2026).

/// One country: its ISO 3166-1 alpha-2 code, its E.164 calling code (no "+") and its name in Arabic and English.
class Country {
  const Country(this.iso, this.dial, this.ar, this.en);

  final String iso;
  final String dial;
  final String ar;
  final String en;

  /// The name in the language the app is showing.
  String name(String locale) => locale == 'en' ? en : ar;
}

const String kDefaultCountry = ${dart(DEFAULT_COUNTRY)};

const List<Country> kCountries = [
${COUNTRIES.map((c) => `  Country(${dart(c.iso)}, ${dart(c.dial)}, ${dart(c.ar)}, ${dart(c.en)}),`).join("\n")}
];

/// The country with [iso], or Qatar when the stored choice is not one we offer any more.
Country countryByIso(String iso) => kCountries.firstWhere((c) => c.iso == iso,
    orElse: () => kCountries.firstWhere((c) => c.iso == kDefaultCountry));
`;
}

export const WEB_FILE = path.join(ROOT, "web", "countries.js");
export const DART_FILE = path.join(ROOT, "app", "lib", "data", "countries.dart");

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(WEB_FILE, webSource());
  writeFileSync(DART_FILE, dartSource());
  console.log(`[countries] ${COUNTRIES.length} countries -> web/countries.js, app/lib/data/countries.dart`);
}
