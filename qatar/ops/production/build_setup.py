"""Builds ops/production/setup.sql: the one script that sets up the HerZone production database (paste it into the
Supabase SQL Editor of herzone-production). Contents, in order:
  1. every migration in db/migrations (schema, functions, policies, scheduled jobs)
  2. ops/production/reference.sql (city, budget tiers, fee, cancellation policy, production settings)
  3. the current questionnaire (QA-2026-04) as a DRAFT: the owner publishes it once her admin account exists
No test data, no people, no secrets. Run: python3 qatar/ops/production/build_setup.py"""
import pathlib
import re

HERE = pathlib.Path(__file__).parent
QATAR = HERE.parent.parent
migrations = sorted((QATAR / "db" / "migrations").glob("[0-9][0-9][0-9]_*.sql"))

questionnaire = (QATAR / "ops" / "seed_questionnaire_v4.sql").read_text()
publish = re.compile(r"\n  UPDATE questionnaire_versions SET status = 'retired'.*?WHERE id = v;\n", re.S)
assert len(publish.findall(questionnaire)) == 1, "seed_questionnaire_v4.sql changed: update build_setup.py"
draft = publish.sub("\n  -- published later by the owner (needs her admin account, NMX-20)\n", questionnaire)
assert "a003" not in draft, "no reference to the staging owner may remain"

parts = ["-- HerZone production database setup. GENERATED by qatar/ops/production/build_setup.py; do not edit by hand.\n"
         "-- Paste the whole file into the Supabase SQL Editor of herzone-production and run it once.\n"]
for m in migrations:
    parts.append(f"\n-- ==================== {m.name}\n{m.read_text()}")
parts.append(f"\n-- ==================== production reference data\n{(HERE / 'reference.sql').read_text()}")
parts.append(f"\n-- ==================== questionnaire QA-2026-04 (draft)\n{draft}")
parts.append("\n-- ==================== done\nRESET search_path;\nSELECT 'HerZone production setup complete' AS result;\n")

out = HERE / "setup.sql"
out.write_text("".join(parts))
print(f"wrote {out} ({out.stat().st_size // 1024} KB, {len(migrations)} migrations)")
